#!/usr/bin/env bash
# warmpool.sh — prints k8s/warmpool.yaml: one SandboxTemplate and one warm
# SandboxWarmPool per agent under images/agent/agents.
#
# Usage: k8s/warmpool.sh > k8s/warmpool.yaml   (or: make warmpool)
#
# Each template runs images/agent's image for the agent, named
# <agent>-template, and its pool <agent>-pool. The agent's agent.env may set
# PULL_POLICY (default Always) and MEMORY_REQUEST (default 128Mi); a boot.sh
# beside it runs in the start command before the sandbox idles.
set -euo pipefail

root=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
agents=$root/images/agent/agents

cat <<'EOF'
# Generated by k8s/warmpool.sh from images/agent/agents. Do not edit by hand;
# run make warmpool. One template and one warm standby per coding agent.
# Claim a pool with k8s/claim.yaml, sbx, or the dashboard.
---
apiVersion: v1
kind: Namespace
metadata:
  name: nightshift
  labels:
    kubernetes.io/metadata.name: nightshift
EOF

for dir in "$agents"/*/; do
  name=$(basename "$dir")
  [ -f "$dir/agent.env" ] || continue
  PULL_POLICY="" MEMORY_REQUEST=""
  # shellcheck source=/dev/null
  . "$dir/agent.env"
  boot=""
  if [ -f "$dir/boot.sh" ]; then
    # Indent into the block scalar, leaving blank lines blank.
    boot=$(grep -Ev '^# (shellcheck |Inlined into |the logins are untarred)' "$dir/boot.sh" |
      sed 's/^\(.\)/          \1/')
    boot=$boot$'\n'
  fi
  cat <<EOF
---
apiVersion: extensions.agents.x-k8s.io/v1beta1
kind: SandboxTemplate
metadata:
  name: $name-template
  namespace: nightshift
spec:
  podTemplate:
    spec:
      restartPolicy: OnFailure
      containers:
      - name: agent
        image: ghcr.io/tmih06/nightshift-$name:latest
        imagePullPolicy: ${PULL_POLICY:-Always}
        command:
        - sh
        - -c
        - |
          c=/etc/nightshift/creds/creds.tar
          if [ -f "\$c" ]; then
            tar -xf "\$c" -C "\$HOME" 2>/dev/null || true
          fi
${boot}          exec sleep infinity
        resources:
          requests:
            cpu: 100m
            memory: ${MEMORY_REQUEST:-128Mi}
          limits:
            cpu: 1000m
            memory: 2Gi
        envFrom:
        - configMapRef:
            name: sandbox-egress-env
            optional: true
        volumeMounts:
        - name: agent-creds
          mountPath: /etc/nightshift/creds
          readOnly: true
        - name: egress-ca
          mountPath: /etc/nightshift/ca
          readOnly: true
      volumes:
      - name: agent-creds
        secret:
          secretName: agent-creds
          optional: true
      - name: egress-ca
        configMap:
          name: egress-ca
          optional: true
---
apiVersion: extensions.agents.x-k8s.io/v1beta1
kind: SandboxWarmPool
metadata:
  name: $name-pool
  namespace: nightshift
spec:
  updateStrategy:
    type: Recreate
  replicas: 1
  sandboxTemplateRef:
    name: $name-template
EOF
done
