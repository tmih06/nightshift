package repoview

import (
	"strings"

	"github.com/tmih06/nightshift/internal/cluster"
)

func dnsSlug(s string) string {
	var b strings.Builder
	for _, r := range strings.ToLower(s) {
		if (r >= 'a' && r <= 'z') || (r >= '0' && r <= '9') {
			b.WriteRune(r)
		} else {
			b.WriteByte('-')
		}
	}
	return strings.Trim(b.String(), "-")
}

func repoSlug(repo string) string {
	return dnsSlug(strings.ReplaceAll(repo, "/", "-"))
}

// sandboxMatchesRepo reports whether box is attached to a volume belonging to repo.
func sandboxMatchesRepo(box ActiveSandbox, repo string) bool {
	if repo == "" || box.Volume == "" {
		return false
	}
	slug := repoSlug(repo)
	if slug == "" {
		return false
	}
	vol := strings.ToLower(box.Volume)
	if strings.HasPrefix(vol, "pr-"+slug+"-") ||
		strings.HasPrefix(vol, "issue-"+slug+"-") ||
		strings.HasPrefix(vol, "repo-"+slug) ||
		strings.HasPrefix(vol, "branch-"+slug) {
		return true
	}
	// Handle hashed long volume names generated by cluster.VolumeName / IssueVolumeName.
	// Check prefix before any truncation hash: e.g. "pr-<first20>".
	if len(slug) > 20 {
		short := slug[:20]
		if strings.HasPrefix(vol, "pr-"+short) || strings.HasPrefix(vol, "issue-"+short) || strings.HasPrefix(vol, "repo-"+short) {
			return true
		}
	}
	return false
}

func hasSandboxForRepo(boxes []ActiveSandbox, repo string) bool {
	for _, b := range boxes {
		if sandboxMatchesRepo(b, repo) {
			return true
		}
	}
	return false
}

func sandboxesForRepo(boxes []ActiveSandbox, repo string) []ActiveSandbox {
	var out []ActiveSandbox
	for _, b := range boxes {
		if sandboxMatchesRepo(b, repo) {
			out = append(out, b)
		}
	}
	return out
}

func sandboxForPR(boxes []ActiveSandbox, repo string, number int) (ActiveSandbox, bool) {
	if repo == "" || number <= 0 {
		return ActiveSandbox{}, false
	}
	want := cluster.VolumeName(repo, number)
	for _, b := range boxes {
		if strings.EqualFold(b.Volume, want) {
			return b, true
		}
	}
	return ActiveSandbox{}, false
}

func sandboxForIssue(boxes []ActiveSandbox, repo string, number int) (ActiveSandbox, bool) {
	if repo == "" || number <= 0 {
		return ActiveSandbox{}, false
	}
	want := cluster.IssueVolumeName(repo, number)
	for _, b := range boxes {
		if strings.EqualFold(b.Volume, want) {
			return b, true
		}
	}
	return ActiveSandbox{}, false
}

func sandboxForBranch(boxes []ActiveSandbox, repo, branch string) (ActiveSandbox, bool) {
	if repo == "" || branch == "" {
		return ActiveSandbox{}, false
	}
	wantExact := cluster.RepoVolumeName(repo, branch)
	for _, b := range boxes {
		if strings.EqualFold(b.Volume, wantExact) {
			return b, true
		}
	}
	rSlug := repoSlug(repo)
	bSlug := dnsSlug(branch)
	if rSlug == "" || bSlug == "" {
		return ActiveSandbox{}, false
	}
	want1 := "repo-" + rSlug + "-" + bSlug
	want2 := "branch-" + rSlug + "-" + bSlug
	for _, b := range boxes {
		vol := strings.ToLower(b.Volume)
		if vol == want1 || vol == want2 ||
			(sandboxMatchesRepo(b, repo) && strings.Contains(vol, bSlug)) {
			return b, true
		}
	}
	return ActiveSandbox{}, false
}
